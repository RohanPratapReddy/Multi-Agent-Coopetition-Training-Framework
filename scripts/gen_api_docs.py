#!/usr/bin/env python
"""Render the route table of docs/api.md from ``mactf.http.openapi.schema()``.

    python scripts/gen_api_docs.py           rewrite the table between the markers
    python scripts/gen_api_docs.py --check   exit 1 when the committed table is stale

Only the table between ``<!-- routes:begin -->`` and ``<!-- routes:end -->`` is generated; the
prose around it is written by hand. ``tests/contrib_api/test_openapi_in_sync.py`` runs the check.
"""
from __future__ import annotations

import argparse
import copy
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "api.md"
BEGIN = "<!-- routes:begin (generated by scripts/gen_api_docs.py; do not edit) -->"
END = "<!-- routes:end -->"
HEADER = "| Method | Path | `operationId` | Summary |"
_ORDER = {"get": 0, "post": 1, "put": 2, "patch": 3, "delete": 4}


def document() -> dict:
    """The OpenAPI document of a server with the API app installed and default settings."""
    sys.path.insert(0, str(ROOT))
    from mactf import apps, conf
    from mactf.http import openapi, urls

    values = copy.deepcopy(conf.DEFAULTS)
    values["INSTALLED_APPS"] = [*values["INSTALLED_APPS"], "mactf.contrib.api"]
    conf._settings = conf.Settings(values)
    apps.reset_registry()
    apps.populate()
    urls.clear_url_caches()
    return openapi.schema(title="MACTF", version="1")


def table(doc: dict) -> str:
    rows = []
    for path, item in doc["paths"].items():
        for method, operation in item.items():
            summary = " ".join(str(operation.get("summary", "")).split()).replace("|", "\\|")
            rows.append((path, _ORDER.get(method, 9), method.upper(), operation["operationId"], summary))
    rows.sort()
    lines = [HEADER, "|---|---|---|---|"]
    lines += [f"| {method} | `{path}` | `{op}` | {summary} |" for path, _, method, op, summary in rows]
    return "\n".join(lines)


def render(current: str, doc: dict) -> str:
    block = f"{BEGIN}\n{table(doc)}\n{END}"
    if BEGIN in current:
        head, _, rest = current.partition(BEGIN)
        _, _, tail = rest.partition(END)
        return head + block + tail
    start = current.index(HEADER)
    end = start
    lines = current[start:].split("\n")
    count = 0
    for line in lines:
        if not line.startswith("|"):
            break
        count += len(line) + 1
    end = start + count
    return current[:start] + block + "\n" + current[end:].lstrip("\n") if current[end:].strip() else current[:start] + block + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/api.md is stale")
    args = parser.parse_args(argv)
    current = TARGET.read_text(encoding="utf-8")
    wanted = render(current, document())
    if args.check:
        if wanted != current:
            sys.stdout.writelines(difflib.unified_diff(
                current.splitlines(True), wanted.splitlines(True), "docs/api.md", "generated"))
            print("docs/api.md is stale: python scripts/gen_api_docs.py", file=sys.stderr)
            return 1
        return 0
    if wanted != current:
        TARGET.write_text(wanted, encoding="utf-8")
        print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
